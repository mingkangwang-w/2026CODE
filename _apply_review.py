# ============================================================ 图号重排
# 原图注为 1,2,3,4,5,6,[缺7],8,...,24。补上缺号后其后一律减 1，使编号连续。
FIGMAP = {n: n - 1 for n in range(8, 25)}


def renumber_figs(text):
    """把图 8..图 24 的引用与图注统一减 1。

    必须把「图 10、11」这类合并图注里的每个编号都算上——只改第一个会留下
    「图 9、11」这种半新半旧的编号，图中恰好因此缺 10 和 16。
    """
    def rep(m):
        nums = [int(n) for n in re.findall(r'\d+', m.group(0))]
        new = [FIGMAP.get(n, n) for n in nums]
        if new == nums:
            return m.group(0)              # 图 1–图 6 不受影响，不着色
        return O('图 ' + '、'.join(str(n) for n in new))
    return re.sub(r'图\s*\d+(?:\s*[、,，]\s*\d+)*', rep, text)


