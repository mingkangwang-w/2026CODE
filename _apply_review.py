def apply(text, edits):
    hit, miss = 0, []
    for pair in edits:
        old, new = pair[0], pair[1]
        if old == new:
            continue
        if old in text:
            text = text.replace(old, new, 1)
            hit += 1
        else:
            miss.append(old[:48])
    return text, hit, miss


